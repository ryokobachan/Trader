export type StrategyTranslationKey = keyof typeof EN_STRATEGY_MESSAGES;
export type StrategyTranslationParameters = Readonly<Record<string, string | number>>;

export function strategyTranslate(
  locale: Locale,
  key: StrategyTranslationKey,
  parameters?: StrategyTranslationParameters,
) {
  const message = (locale === "ja" ? JA_STRATEGY_MESSAGES : EN_STRATEGY_MESSAGES)[key];
  if (!parameters) return message;
  return message.replace(/\{([a-zA-Z0-9_]+)\}/g, (token, name: string) => {
    const value = parameters[name];
    return value === undefined ? token : String(value);
  });
}

export function createStrategyTranslator(locale: Locale) {
  return (key: StrategyTranslationKey, parameters?: StrategyTranslationParameters) => (
    strategyTranslate(locale, key, parameters)
  );
}

export function strategyDurationLabel(locale: Locale, duration: string) {
  return duration === "全期間" ? strategyTranslate(locale, "duration.all") : duration;
}

export function portfolioTabLabel(locale: Locale, tab: string) {
  if (tab === "概要") return strategyTranslate(locale, "tab.overview");
  if (tab === "保有銘柄") return strategyTranslate(locale, "tab.holdings");
  if (tab === "取引") return strategyTranslate(locale, "tab.transactions");
  return tab;
}

export function portfolioChartModeLabel(locale: Locale, mode: string) {
  if (mode === "資産額") return strategyTranslate(locale, "chart.assetValue");
  if (mode === "パフォーマンス") return strategyTranslate(locale, "chart.performance");
  return mode;
}

export function portfolioTransactionTabLabel(locale: Locale, tab: string) {
  if (tab === "取引") return strategyTranslate(locale, "transactions.trades");
  if (tab === "現金") return strategyTranslate(locale, "transactions.cash");
  return tab;
}

export function portfolioTransactionSideLabel(locale: Locale, side: string) {
  if (side === "買付") return strategyTranslate(locale, "transaction.buy");
  if (side === "売却") return strategyTranslate(locale, "transaction.sell");
  if (side === "配当") return strategyTranslate(locale, "transaction.dividend");
  return side;
}

export function strategyTechnicalRatingLabel(locale: Locale, rating: string) {
  if (rating === "強い買い") return strategyTranslate(locale, "rating.strongBuy");
  if (rating === "買い") return strategyTranslate(locale, "rating.buy");
  if (rating === "中立") return strategyTranslate(locale, "rating.neutral");
  if (rating === "売り") return strategyTranslate(locale, "rating.sell");
  if (rating === "強い売り") return strategyTranslate(locale, "rating.strongSell");
  return rating;
}
