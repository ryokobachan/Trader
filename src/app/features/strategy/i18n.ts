export type StrategyTranslationKey = keyof typeof EN_STRATEGY_MESSAGES;
export type StrategyTranslationParameters = Readonly<Record<string, string | number>>;

export function strategyTranslate(
  locale: Locale,
  key: StrategyTranslationKey,
  parameters?: StrategyTranslationParameters,
) {
  const message = (locale === "ja" ? JA_STRATEGY_MESSAGES : EN_STRATEGY_MESSAGES)[key];
  if (!parameters) return message;
  return message.replace(/\{([a-zA-Z0-9_]+)\}/g, (token, name: string) => {
    const value = parameters[name];
    return value === undefined ? token : String(value);
  });
}

export function createStrategyTranslator(locale: Locale) {
  return (key: StrategyTranslationKey, parameters?: StrategyTranslationParameters) => (
    strategyTranslate(locale, key, parameters)
  );
}

export function strategyDurationLabel(locale: Locale, duration: string) {
  return duration === "全期間" ? strategyTranslate(locale, "duration.all") : duration;
}

