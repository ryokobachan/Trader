export const TRANSLATIONS: Readonly<Record<Locale, TranslationDictionary>> = {
  en: EN_MESSAGES,
  ja: JA_MESSAGES,
};

type LocaleStorage = Pick<Storage, "getItem" | "setItem">;

export function isLocale(value: unknown): value is Locale {
  return typeof value === "string"
    && SUPPORTED_LOCALES.some((locale) => locale.code === value);
}

export function normalizeLocale(value: unknown, fallback: Locale = DEFAULT_LOCALE): Locale {
  return isLocale(value) ? value : fallback;
}

export function readStoredLocale(
  storage: Pick<LocaleStorage, "getItem"> | null | undefined,
  fallback: Locale = DEFAULT_LOCALE,
): Locale {
  if (!storage) return fallback;

  try {
    return normalizeLocale(storage.getItem(LOCALE_STORAGE_KEY), fallback);
  } catch {
    return fallback;
  }
}

export function writeStoredLocale(
  storage: Pick<LocaleStorage, "setItem"> | null | undefined,
  locale: Locale,
): boolean {
  if (!storage || !isLocale(locale)) return false;

  try {
    storage.setItem(LOCALE_STORAGE_KEY, locale);
    return true;
  } catch {
    return false;
  }
}

function interpolate(message: string, parameters?: TranslationParameters) {
  if (!parameters) return message;

  return message.replace(/\{([a-zA-Z0-9_]+)\}/g, (token, name: string) => {
    const value = parameters[name];
    return value === undefined ? token : String(value);
  });
}

export function translate(
  locale: Locale,
  key: string,
  parameters?: TranslationParameters,
): string {
  const message = TRANSLATIONS[locale][key]
    ?? TRANSLATIONS[DEFAULT_LOCALE][key]
    ?? key;
  return interpolate(message, parameters);
}

export type I18nContextValue = Readonly<{
  locale: Locale;
  setLocale: (locale: Locale) => void;
  t: (key: string, parameters?: TranslationParameters) => string;
  supportedLocales: typeof SUPPORTED_LOCALES;
}>;

const I18nContext = createContext<I18nContextValue | null>(null);

const localeStoreListeners = new Set<() => void>();
let inMemoryLocale: Locale | null = null;

function readLocaleSnapshot(fallback: Locale) {
  if (typeof window === "undefined") return fallback;
  if (inMemoryLocale === null) {
    migrateProductStorage(window.localStorage);
    inMemoryLocale = readStoredLocale(window.localStorage, fallback);
  }
  return inMemoryLocale;
}

function subscribeToLocaleStore(listener: () => void) {
  localeStoreListeners.add(listener);

  const handleStorage = (event: StorageEvent) => {
    if (event.key !== LOCALE_STORAGE_KEY) return;
    inMemoryLocale = normalizeLocale(event.newValue);
    listener();
  };

  window.addEventListener("storage", handleStorage);
  return () => {
    localeStoreListeners.delete(listener);
    window.removeEventListener("storage", handleStorage);
  };
}

function updateLocaleStore(locale: Locale) {
  if (!isLocale(locale)) return;
  inMemoryLocale = locale;
  writeStoredLocale(window.localStorage, locale);
  localeStoreListeners.forEach((listener) => listener());
}

export type I18nProviderProps = Readonly<{
  children?: ReactNode;
  initialLocale?: Locale;
}>;

export function I18nProvider({
  children,
  initialLocale = DEFAULT_LOCALE,
}: I18nProviderProps) {
  const validatedInitialLocale = normalizeLocale(initialLocale);
  const getLocaleSnapshot = useCallback(
    () => readLocaleSnapshot(validatedInitialLocale),
    [validatedInitialLocale],
  );
  const getServerLocaleSnapshot = useCallback(
    () => validatedInitialLocale,
    [validatedInitialLocale],
  );
  const locale = useSyncExternalStore(
    subscribeToLocaleStore,
    getLocaleSnapshot,
    getServerLocaleSnapshot,
  );

  useEffect(() => {
    document.documentElement.lang = locale;
  }, [locale]);

  const setLocale = useCallback((nextLocale: Locale) => {
    updateLocaleStore(nextLocale);
  }, []);

  const t = useCallback(
    (key: string, parameters?: TranslationParameters) => translate(locale, key, parameters),
    [locale],
  );

  const value = useMemo<I18nContextValue>(() => ({
    locale,
    setLocale,
    t,
    supportedLocales: SUPPORTED_LOCALES,
  }), [locale, setLocale, t]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nContextValue {
  const context = useContext(I18nContext);
  if (!context) {
    throw new Error("useI18n must be used within an I18nProvider");
  }
  return context;
}
